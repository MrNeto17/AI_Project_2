def get_calendar():
    # Fix known typo and parse CSV into list of dicts
    cleaned = CALENDAR_CSV.replace("15/13/2027", "15/03/2027")
    reader = csv.DictReader(io.StringIO(cleaned.strip()))
    rows = [r for r in reader]
    return rows


def get_inputs_for_day(row):
    # Weather: NOT_RAINING -> 1, RAINING -> 2
    w = "1" if row.get("weather", "").strip() == "NOT_RAINING" else "2"

    # Event mapping
    e_map = {"NONE": "1", "HOLIDAY": "2", "SMALL_EVENT": "3", "BIG_EVENT": "4"}
    e = e_map.get(row.get("event", "").strip(), "1")

    # Build input sequence per spec for ONE day
    # Note: We do NOT include the "Go to next day" input here because
    # we are restarting main.py for each day.
    inputs = [
        w,  # Weather
        e,  # Event
        "",  # Multiplier (Enter for default 1.0)
        "y",  # Confirm
        "1",  # Model (Heuristic)
        "y",  # Proceed with simulation
        "n",  # Real-time correctness (disable)
        "0.0000000000000001",  # Seconds per minute
        "n",  # Go to next day? NO (Exit program after this day)
    ]

    return "\n".join(inputs) + "\n"


def main():
    days = get_calendar()
    total = len(days)
    log_path = "simulation_log.txt"

    # Open log file in append mode so we don't overwrite previous days
    with open(log_path, "a", encoding="utf-8") as logf:
        for i, row in enumerate(days):
            date_str = row.get("date", "unknown")
            print(
                f"Starting Day {i + 1}/{total}: {date_str} ({row.get('event')}, {row.get('weather')})..."
            )

            # Log separator for readability
            logf.write(f"\n{'=' * 20} DAY {i + 1}: {date_str} {'=' * 20}\n")
            logf.flush()

            try:
                # Start a NEW process for each day
                proc = subprocess.Popen(
                    [sys.executable, "main.py"],
                    stdin=subprocess.PIPE,
                    stdout=logf,
                    stderr=subprocess.STDOUT,  # Merge stderr into stdout for cleaner logs
                    text=True,
                )

                input_block = get_inputs_for_day(row)

                if proc.stdin:
                    proc.stdin.write(input_block)
                    proc.stdin.close()  # Close stdin to signal EOF

                # Wait for this day to finish completely
                proc.wait()

                print(f"Finished Day {i + 1}/{total}: {date_str}")

            except Exception as e:
                print(f"Error on Day {i + 1} ({date_str}): {e}")
                logf.write(f"ERROR: {e}\n")
                break

    print("Simulation complete. Logs: simulation_log.txt")


if __name__ == "__main__":
    main()
